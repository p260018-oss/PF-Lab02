#include <stdio.h>
int main() {
    printf("=================== C ESCAPE SEQUENCE REFERENCE ================\n");
    printf("To print a double quote, write:       \t\\\" \n");
    printf("To print a literal backslash, write:  \t\\\\ \n");
    printf("To print a newline break, write:      \t\\n  \n");
    printf("To print a horizontal tab stop, write:\t\\t  \n");
    printf("To print a percent sign, write:       \t%%%  \n");
    printf("=================================================================");
    return 0;
}